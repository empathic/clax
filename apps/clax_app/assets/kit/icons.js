/** The SVG markup of icon `name` (`size` px, `stroke` width; `label` makes it an image with that accessible name). */
export function icon(name, { size = 24, stroke = 2, label } = {}) {
  const p = P[name];
  if (p === undefined) return '';
  const a = label ? `role="img" aria-label="${String(label).replace(/[&"<]/g, '')}"` : 'aria-hidden="true"';
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round" ${a}>${p}</svg>`;
}
