// Builds Clax's public design tokens from web/sdk/tokens/clax.tokens.json
// with Style Dictionary, into web/sdk/tokens/dist/:
//
//   clax.css               every role as a --clax-* custom property, the
//                          profile chosen by the page's data-theme or
//                          .clax-light / .clax-dark class, else the system's
//                          colour scheme; then prefers-contrast: more,
//                          forced-colors and prefers-reduced-motion
//   clax.theme.tokens.json every profile's roles resolved, in Clax's role
//                          names (W3C Design Tokens): a template for the
//                          SDK's `theme` option, which reads theme.light,
//                          theme.dark and base
//   clax.theme.ts          the same as a typed module, and ClaxRole
//
// Style Dictionary (pinned in package.json) reads the token file, follows
// its aliases and names each token; each value is written by tokens.ts's
// cssValue, the same function that writes the overlay's and the shell's
// generated regions, so the public properties and the overlay's fallbacks
// cannot drift apart. The outputs are committed and
// sdk/src/build-tokens.test.ts fails while they differ from a build.
//
//   node scripts/build-tokens.ts           write the outputs
//   node scripts/build-tokens.ts --check   write nothing; exit 1 on a difference
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import StyleDictionary from "style-dictionary";
import type { DesignTokens, TransformedToken } from "style-dictionary/types";
import { cssValue, PUBLIC_PREFIX, resolve, type TokenGroup, typeOf } from "../sdk/src/tokens.ts";

/** The colour profiles, in the token file's `theme` group. */
export const PROFILES = ["light", "dark", "light-more", "dark-more", "forced"] as const;
export type Profile = (typeof PROFILES)[number];

const HEADER = "Generated by web/scripts/build-tokens.ts from web/sdk/tokens/clax.tokens.json. Do not edit.";

/** The light profile's elements: the root unless a page says otherwise. */
const LIGHT = `:root, [data-theme="light"], .clax-light`;
/** The root under the system's dark scheme, unless it is marked light. */
const ROOT_DARK = `:root:where(:not([data-theme="light"], .clax-light))`;
/** An element marked dark. */
const DARK = `[data-theme="dark"], .clax-dark`;
/** Every element a profile is chosen on. */
const ANY = `:root, [data-theme], .clax-light, .clax-dark`;

/** A token's place: its profile (or `base`, `reduced-motion`) and its role. */
function place(path: string[]): { group: Profile | "base" | "reduced-motion"; role: string } | null {
  if (path[0] === "theme" && (PROFILES as readonly string[]).includes(path[1])) return { group: path[1] as Profile, role: path.slice(2).join("-") };
  if (path[0] === "base" || path[0] === "reduced-motion") return { group: path[0], role: path.slice(1).join("-") };
  return null;
}

export interface Built { css: string; json: string; ts: string }

/** The outputs for a token file in Clax's shape. */
export async function buildTokens(file: TokenGroup): Promise<Built> {
  const sd = new StyleDictionary({
    tokens: structuredClone(file) as DesignTokens,
    log: { verbosity: "silent", warnings: "disabled" },
    hooks: {
      transforms: {
        "clax/name": { type: "name", transform: (t: TransformedToken) => `${PUBLIC_PREFIX.slice(2)}${place(t.path)?.role ?? t.path.join("-")}` },
        "clax/css": { type: "value", transitive: true, transform: (t: TransformedToken) => cssValue(resolve(file, t.path.join(".")), typeOf(file, t.path.join("."))) },
      },
    },
    platforms: { clax: { transforms: ["clax/name", "clax/css"] } },
  });
  const { allTokens } = await sd.getPlatformTokens("clax");

  const groups = new Map<string, { role: string; name: string; value: string; link: string | null; type: string | undefined }[]>();
  for (const t of allTokens) {
    const at = place(t.path);
    if (!at) continue;
    // An alias to a role of its own profile stays a link (`--clax-accent: var(--clax-agent)`), as
    // in the overlay's regions, so a page that sets the one moves the other.
    const alias = typeof t.original.$value === "string" ? /^\{([^{}]+)\}$/.exec(t.original.$value)?.[1].split(".") : undefined;
    const to = alias ? place(alias) : null;
    const list = groups.get(at.group) ?? [];
    list.push({ role: at.role, name: t.name, value: String(t.$value), link: to && to.group === at.group ? `var(${PUBLIC_PREFIX}${to.role})` : null, type: typeOf(file, t.path.join(".")) });
    groups.set(at.group, list);
  }
  const decls = (group: string) => (groups.get(group) ?? []).map(d => `--${d.name}: ${d.link ?? d.value};`);
  const rule = (selector: string, lines: string[], indent = "") => [`${indent}${selector} {`, ...lines.map(l => `${indent}  ${l}`), `${indent}}`];
  const media = (query: string, ...rules: string[][]) => [`@media ${query} {`, ...rules.flat().map(l => `  ${l}`), "}"];

  // Every block declares every role of its profile, so which applies is
  // decided by order alone: each selector has one class's specificity
  // (:where() adds none), and a later block wins.
  const css = [
    `/* ${HEADER}`,
    "   Map a design system onto Clax by setting these properties on any",
    "   ancestor of the overlay, or load this file for Clax's own palette:",
    "   web/sdk/tokens/README.md. */",
    ...rule(LIGHT, [...decls("light"), ...decls("base")]),
    ...media("(prefers-color-scheme: dark)", rule(ROOT_DARK, decls("dark"))),
    ...rule(DARK, decls("dark")),
    ...media("(prefers-contrast: more)", rule(LIGHT, decls("light-more"))),
    ...media("(prefers-contrast: more) and (prefers-color-scheme: dark)", rule(ROOT_DARK, decls("dark-more"))),
    ...media("(prefers-contrast: more)", rule(DARK, decls("dark-more"))),
    ...media("(forced-colors: active)", rule(ANY, decls("forced"))),
    ...media("(prefers-reduced-motion: reduce)", rule(ANY, decls("reduced-motion"))),
    "",
  ].join("\n");

  // The template: each token as { $type, $value } in its role's place, the
  // value as CSS writes it (a host's own file may use any DTCG value).
  const tree: Record<string, unknown> = { $description: `${HEADER} Clax's roles in every profile, resolved: copy it, change the values, and pass it as the SDK's \`theme\` option (which reads theme.light, theme.dark and base).` };
  for (const [group, list] of groups) {
    const node: Record<string, unknown> = {};
    for (const d of list) {
      const path = group === "base" || group === "reduced-motion" ? [d.role] : rolePath(file, group as Profile, d.role);
      let o = node;
      for (const p of path.slice(0, -1)) o = (o[p] ??= {}) as Record<string, unknown>;
      o[path.at(-1)!] = d.type ? { $type: d.type, $value: d.value } : { $value: d.value };
    }
    if (group === "base" || group === "reduced-motion") tree[group] = node;
    else ((tree.theme ??= {}) as Record<string, unknown>)[group] = node;
  }
  const json = JSON.stringify(tree, null, 2) + "\n";

  const ts = [
    `// ${HEADER}`,
    "/** Clax's roles in every profile, resolved, as CSS values: clax.theme.tokens.json as a module. */",
    `export const claxTheme = ${JSON.stringify(tree, null, 2)} as const;`,
    "",
    "/** A colour role of Clax's (`bg`, `fg`, `accent`, `tag-red-bg`, …), as a --clax-* property names it with `-`. */",
    `export type ClaxRole = ${[...new Set((groups.get("light") ?? []).map(d => JSON.stringify(d.role)))].join(" | ")};`,
    "",
  ].join("\n");
  return { css, json, ts };
}

/** A role's path in its profile's group (`tag-red-bg` is tag.red.bg), read
 * from the token file, since a role name may hold a `-` (`border-strong`). */
function rolePath(file: TokenGroup, profile: Profile, role: string): string[] {
  const walk = (g: unknown, rest: string, path: string[]): string[] | null => {
    if (typeof g !== "object" || g === null) return null;
    for (const k of Object.keys(g)) {
      if (k.startsWith("$")) continue;
      if (rest === k) return [...path, k];
      if (rest.startsWith(`${k}-`)) { const r = walk((g as Record<string, unknown>)[k], rest.slice(k.length + 1), [...path, k]); if (r) return r; }
    }
    return null;
  };
  const r = walk((file.theme as TokenGroup)[profile], role, []);
  if (!r) throw new Error(`no role ${role} in theme.${profile}`);
  return r;
}

/** Where the outputs are written. */
export const OUTPUTS = { css: "sdk/tokens/dist/clax.css", json: "sdk/tokens/dist/clax.theme.tokens.json", ts: "sdk/tokens/dist/clax.theme.ts" } as const;

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const web = join(dirname(fileURLToPath(import.meta.url)), "..");
  const file = JSON.parse(readFileSync(join(web, "sdk/tokens/clax.tokens.json"), "utf8")) as TokenGroup;
  const built = await buildTokens(file);
  const check = process.argv.includes("--check");
  let differs = false;
  for (const k of Object.keys(OUTPUTS) as (keyof Built)[]) {
    const p = join(web, OUTPUTS[k]);
    let old = "";
    try { old = readFileSync(p, "utf8"); } catch { /* not built yet */ }
    if (old === built[k]) continue;
    differs = true;
    if (check) console.error(`${OUTPUTS[k]} differs from a build: run node scripts/build-tokens.ts`);
    else { mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, built[k]); console.log(`wrote ${OUTPUTS[k]}`); }
  }
  if (check && differs) process.exit(1);
}
