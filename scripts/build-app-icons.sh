#!/usr/bin/env bash
# scripts/build-app-icons.sh [--check | --list | --preview DIR]
#
# Renders the Clax app's icons from the mark (design/mark.json) and the
# colours design/tokens.json gives it (docs/superpowers/specs/
# 2026-10-18-professional-ui-design.md §5.11), and writes them where the
# Android and macOS builds read them:
#
# - Android: the adaptive icon (mipmap-anydpi-v26/ic_launcher.xml and
#   ic_launcher_round.xml: the `bg` background, the mark as a vector
#   foreground, and a one-colour monochrome layer for themed icons), the
#   legacy mipmap-*dpi PNGs and the 512 px store icon;
# - macOS: AppIcon.appiconset (16 to 1024 px on Apple's grid) and the Icon
#   Composer bundle AppIcon.icon (the background, each arc and the dot as
#   layers, with light, dark and tinted appearances).
#
# PNGs are rendered with rsvg-convert: RSVG_CONVERT when set, else the first
# on PATH or in a Homebrew prefix; the run fails naming it, before writing
# anything, when there is none. Every output and its size is data
# (ANDROID_DENSITIES, MACOS_SLOTS, TARGETS below), so another platform's set
# is one more target.
#
# apps/clax_app/icons/SOURCE.sha256 records the hash of what the icons were
# rendered from: the mark, the colours they use and this script. --check
# writes nothing: it fails, naming each file, when that hash, a generated
# text file (the drawables, Contents.json, the .icon's JSON and layers) or a
# rendered PNG is stale or missing. It never compares pixels, so a renderer
# upgrade cannot fail it (//design:icons_sync). --list prints each output as
# `text PATH` or `png PATH SIZE`. --preview DIR renders, into DIR only, what
# the icons look like where they are shown: the adaptive icon under several
# launcher masks with its safe zone, the monochrome layer themed light and
# dark, and the macOS icon light and dark at 1024, 64, 32 and 16 px.
#
# Works from any directory.
set -euo pipefail
exec python3 -I - "$0" "$@" <<'PY'
import hashlib
import json
import math
import os
import re
import shutil
import subprocess
import sys
import tempfile

SCRIPT = sys.argv[1]
ARGS = sys.argv[2:]
ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(SCRIPT)), ".."))
SELF = "scripts/build-app-icons.sh"
MARK = "design/mark.json"
TOKENS = "design/tokens.json"
HASH = "apps/clax_app/icons/SOURCE.sha256"
# The tokens the icons are drawn in; the hash covers these and no others.
COLORS = ("agent", "bg", "fg", "hover", "raised", "you")

RES = "apps/clax_app/android/app/src/main/res"
APPICONSET = "apps/clax_app/macos/Runner/Assets.xcassets/AppIcon.appiconset"
ICON = "apps/clax_app/macos/Runner/AppIcon.icon"

# Android's adaptive icon (§5.11): a 108 dp canvas whose inner 72 dp a
# launcher shows through its mask, the mark 52 dp wide at its centre, inside
# the 66 dp circle no mask cuts.
ADAPTIVE = {"canvas": 108, "visible": 72, "safe": 66, "mark": 52}
# The legacy launcher PNGs: density and pixel size of the 48 dp icon.
ANDROID_DENSITIES = [("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)]
PLAY_STORE = ("apps/clax_app/icons/play-store-512.png", 512)

# Apple's macOS grid (§5.11): a 1024 canvas, an 824 body with radius 185
# continuous corners and the standard drop shadow, the mark 560 wide.
APPLE = {"canvas": 1024, "body": 824, "radius": 185, "mark": 560,
         "shadow": {"dy": 10, "blur": 5, "opacity": 0.3}}
# The macOS icon's small sizes, where the 1024 design scaled down fuses the
# dot with the arcs: px -> the mark's width on the 1024 grid and a simpler
# geometry in the mark's viewBox, with shallower arcs set further out, a
# heavier stroke and a bigger dot, so a gap of about 1.5 px parts each arc
# from the dot at 16 px (and about 2 px at 32). Larger sizes draw the mark.
SMALL_GEOMETRY = {
    "stroke": 3,
    "you": "M1.5 3a5.6667 5.6667 0 0 1 0 10",
    "agent": "M20.5 3a5.6667 5.6667 0 0 0 0 10",
    "dot": {"cx": 11, "cy": 8, "r": 2},
}
APPLE_SMALL = {16: dict(SMALL_GEOMETRY, mark=704), 32: dict(SMALL_GEOMETRY, mark=640)}
# AppIcon.appiconset's slots: (points, scale); the file is app_icon_<px>.png.
MACOS_SLOTS = [(16, 1), (16, 2), (32, 1), (32, 2), (128, 1), (128, 2),
               (256, 1), (256, 2), (512, 1), (512, 2)]

GENERATED = "Generated by scripts/build-app-icons.sh from design/mark.json and design/tokens.json; do not edit."


def die(msg):
    print("build-app-icons.sh: " + msg, file=sys.stderr)
    sys.exit(1)


def read(path):
    with open(os.path.join(ROOT, path), "rb") as f:
        return f.read()


def n(x):
    """A number for SVG and XML: at most four decimals, no trailing zeros."""
    s = ("%.4f" % x).rstrip("0").rstrip(".")
    return "0" if s in ("", "-0") else s


mark = json.loads(read(MARK))
tokens = json.loads(read(TOKENS))["color"]


def color(name, mode):
    v = tokens[name]
    while isinstance(v, str):  # an alias names another token
        v = tokens[v]
    return v[mode]


def palette(mode):
    """The colours of one appearance: `light` or `dark`."""
    return {"you": color("you", mode), "agent": color("agent", mode), "dot": color("fg", mode)}


def source_hash():
    src = {
        "mark": mark,
        "colors": {c: tokens[c] for c in COLORS},
        "script": hashlib.sha256(read(SELF)).hexdigest(),
    }
    return hashlib.sha256(json.dumps(src, sort_keys=True).encode()).hexdigest()


# --- The mark ---------------------------------------------------------------

VW, VH = mark["viewBox"]


def dot_d(dot):
    """A dot as a path: two half arcs (a vector drawable has no circle)."""
    return "M%s %sa%s %s 0 1 0 %s 0a%s %s 0 1 0 %s 0" % (
        n(dot["cx"] - dot["r"]), n(dot["cy"]), n(dot["r"]), n(dot["r"]), n(2 * dot["r"]),
        n(dot["r"]), n(dot["r"]), n(-2 * dot["r"]))


DOT_D = dot_d(mark["dot"])


def outline(d, width):
    """A stroked arc's outline as a filled path: `d` is one circular arc
    (`M x y a r r 0 large sweep dx dy`, the form design/mark.json's arcs
    take), stroked `width` wide with round caps. Icon Composer fills a
    layer's geometry and ignores its stroke."""
    nums = [float(v) for v in re.findall(r"-?\d*\.?\d+", d)]
    if not re.fullmatch(r"\s*M[^A-Za-z]*[aA][^A-Za-z]*", d) or len(nums) != 9 or nums[2] != nums[3]:
        die("an arc outline needs `M x y a r r 0 large sweep dx dy`, not " + d)
    x0, y0, r, _, _, large, sweep, x1, y1 = nums
    if "a" in d:
        x1, y1 = x0 + x1, y0 + y1
    # The centre (SVG's endpoint-to-centre conversion, for a circle).
    mx, my = (x0 + x1) / 2, (y0 + y1) / 2
    hx, hy = (x0 - x1) / 2, (y0 - y1) / 2
    half = math.hypot(hx, hy)
    k = math.sqrt(max(r * r - half * half, 0)) / half
    sign = -1 if large == sweep else 1
    cx, cy = mx + sign * k * hy, my - sign * k * hx
    h = width / 2

    def at(x, y, rr):
        return n(cx + (x - cx) * rr / r), n(cy + (y - cy) * rr / r)

    lg, sw, back = int(large), int(sweep), 1 - int(sweep)
    o0, o1, i0, i1 = at(x0, y0, r + h), at(x1, y1, r + h), at(x0, y0, r - h), at(x1, y1, r - h)
    return ("M%s %sA%s %s 0 %d %d %s %sA%s %s 0 0 %d %s %sA%s %s 0 %d %d %s %sA%s %s 0 0 %d %s %sz" % (
        *o0, n(r + h), n(r + h), lg, sw, *o1,
        n(h), n(h), sw, *i1,
        n(r - h), n(r - h), lg, back, *i0,
        n(h), n(h), sw, *o0))


def placed(cx, cy, width):
    """The transform that puts the mark `width` wide, centred on (cx, cy)."""
    s = width / VW
    return cx - VW * s / 2, cy - VH * s / 2, s


def mark_svg(cx, cy, width, pal, geometry=None):
    """The mark `width` wide at (cx, cy) in `pal`'s colours; `geometry`
    (stroke, you, agent, dot) replaces design/mark.json's shapes."""
    g = geometry or {"stroke": mark["stroke"], "you": mark["you"]["d"],
                     "agent": mark["agent"]["d"], "dot": mark["dot"]}
    tx, ty, s = placed(cx, cy, width)
    return (
        '<g transform="translate(%s %s) scale(%s)">'
        '<path d="%s" fill="none" stroke="%s" stroke-width="%s" stroke-linecap="%s"/>'
        '<path d="%s" fill="none" stroke="%s" stroke-width="%s" stroke-linecap="%s"/>'
        '<path d="%s" fill="%s"/></g>'
    ) % (n(tx), n(ty), n(s),
         g["you"], pal["you"], n(g["stroke"]), mark["cap"],
         g["agent"], pal["agent"], n(g["stroke"]), mark["cap"],
         dot_d(g["dot"]), pal["dot"])


def svg(view, body, size=None, defs=""):
    x, y, w, h = view
    dims = ' width="%s" height="%s"' % (size, size) if size else ""
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="%s %s %s %s"%s>%s%s</svg>\n'
            % (n(x), n(y), n(w), n(h), dims, "<defs>%s</defs>" % defs if defs else "", body))


# --- Android ----------------------------------------------------------------

def vector(pal):
    c = ADAPTIVE["canvas"]
    tx, ty, s = placed(c / 2, c / 2, ADAPTIVE["mark"])
    stroke = 'android:strokeWidth="%s"\n            android:strokeLineCap="%s"' % (n(mark["stroke"]), mark["cap"])
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {GENERATED} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{c}dp"
    android:height="{c}dp"
    android:viewportWidth="{c}"
    android:viewportHeight="{c}">
    <group
        android:translateX="{n(tx)}"
        android:translateY="{n(ty)}"
        android:scaleX="{n(s)}"
        android:scaleY="{n(s)}">
        <path
            android:pathData="{mark["you"]["d"]}"
            android:strokeColor="{pal["you"]}"
            {stroke}/>
        <path
            android:pathData="{mark["agent"]["d"]}"
            android:strokeColor="{pal["agent"]}"
            {stroke}/>
        <path
            android:pathData="{DOT_D}"
            android:fillColor="{pal["dot"]}"/>
    </group>
</vector>
'''


ADAPTIVE_XML = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {GENERATED} -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_bg"/>
    <foreground android:drawable="@drawable/ic_launcher_fg"/>
    <monochrome android:drawable="@drawable/ic_launcher_mono"/>
</adaptive-icon>
'''

MONO = {"you": "#000000", "agent": "#000000", "dot": "#000000"}


def adaptive_svg(size, shape, background, pal, guide=False):
    """The adaptive icon's visible 72 dp, as a launcher shows it through
    `shape` (square, rounded, circle, squircle, teardrop)."""
    c, v = ADAPTIVE["canvas"], ADAPTIVE["visible"]
    o = (c - v) / 2
    clip = mask_path(shape, o, v)
    body = '<g clip-path="url(#m)"><rect x="0" y="0" width="%s" height="%s" fill="%s"/>%s</g>' % (
        c, c, background, mark_svg(c / 2, c / 2, ADAPTIVE["mark"], pal))
    if guide:
        body += ('<circle cx="%s" cy="%s" r="%s" fill="none" stroke="#2f6fd0" stroke-width="0.4" '
                 'stroke-dasharray="1.2 0.8"/>' % (n(c / 2), n(c / 2), n(ADAPTIVE["safe"] / 2)))
    return svg((o, o, v, v), body, size, '<clipPath id="m"><path d="%s"/></clipPath>' % clip)


def mask_path(shape, o, v):
    r = v / 2
    cx = cy = o + r
    if shape == "square":
        return "M%s %sh%sv%sh-%sz" % (n(o), n(o), n(v), n(v), n(v))
    if shape == "circle":
        return "M%s %sa%s %s 0 1 0 %s 0a%s %s 0 1 0 -%s 0z" % (n(o), n(cy), n(r), n(r), n(v), n(r), n(r), n(v))
    if shape == "rounded":
        return continuous_rect(o, o, v, v, v * 0.16)
    if shape == "teardrop":  # a circle with a square bottom-right corner
        return "M%s %sA%s %s 0 0 1 %s %sA%s %s 0 0 1 %s %sL%s %sL%s %sA%s %s 0 0 1 %s %sz" % (
            n(o), n(cy), n(r), n(r), n(cx), n(o), n(r), n(r), n(o + v), n(cy),
            n(o + v), n(o + v), n(cx), n(o + v), n(r), n(r), n(o), n(cy))
    if shape == "squircle":  # |x|^4 + |y|^4 = r^4
        pts = []
        for i in range(240):
            t = 2 * math.pi * i / 240
            ct, st = math.cos(t), math.sin(t)
            pts.append((cx + r * math.copysign(abs(ct) ** 0.5, ct), cy + r * math.copysign(abs(st) ** 0.5, st)))
        return "M" + "L".join("%s %s" % (n(x), n(y)) for x, y in pts) + "z"
    die("no mask shape " + shape)


def android():
