        RES + "/drawable/ic_launcher_fg.xml": ("text", vector(light)),
        RES + "/drawable/ic_launcher_mono.xml": ("text", vector(MONO)),
        RES + "/values/ic_launcher_colors.xml": ("text", f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {GENERATED} -->
<resources>
    <color name="ic_launcher_bg">{color("bg", "light")}</color>
