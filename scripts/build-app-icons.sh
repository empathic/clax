    path, px = PLAY_STORE
    out[path] = ("png", adaptive_svg(px, "square", bg, light), px)
    return out


# --- Apple ------------------------------------------------------------------

# Apple's continuous corner, as (distance from the right edge, distance from
# the top edge) in radii, from the top edge round to the right edge: the
# Bézier approximation of UIBezierPath's rounded rectangle.
CORNER = [
    ("L", (1.52866483, 0)),
    ("C", (1.08849323, 0), (0.86840689, 0), (0.66993427, 0.06549600)),
    ("L", (0.63149399, 0.07491100)),
    ("C", (0.37282392, 0.16905899), (0.16906013, 0.37282401), (0.07491176, 0.63149399)),
    ("L", (0.06549569, 0.66993423)),
    ("C", (0, 0.86840701), (0, 1.08849299), (0, 1.52866483)),
]


def continuous_rect(x, y, w, h, r):
    corners = [
        lambda a, b: (x + w - a * r, y + b * r),      # top right
        lambda a, b: (x + w - b * r, y + h - a * r),  # bottom right
        lambda a, b: (x + a * r, y + h - b * r),      # bottom left
        lambda a, b: (x + b * r, y + a * r),          # top left
    ]
    d = "M%s %s" % (n(x + CORNER[0][1][0] * r), n(y))
    for at in corners:
        for op, *pts in CORNER:
            d += op + " ".join("%s %s" % tuple(n(v) for v in at(*p)) for p in pts)
    return d + "z"


def apple_svg(size, mode):
    """The macOS icon on Apple's 1024 grid: the body, its shadow, the mark
    (APPLE_SMALL's at its sizes)."""
    a = APPLE
    c, b = a["canvas"], a["body"]
    o = (c - b) / 2
    sh = a["shadow"]
    defs = (
        '<filter id="s" x="-10%%" y="-10%%" width="120%%" height="130%%">'
        '<feGaussianBlur in="SourceAlpha" stdDeviation="%s"/><feOffset dy="%s"/>'
        '<feComponentTransfer><feFuncA type="linear" slope="%s"/></feComponentTransfer>'
        '<feMerge><feMergeNode/><feMergeNode in="SourceGraphic"/></feMerge></filter>'
        % (n(sh["blur"]), n(sh["dy"]), n(sh["opacity"]))
    )
    if mode == "light":
        defs += ('<linearGradient id="f" x1="0" y1="0" x2="0" y2="1">'
                 '<stop offset="0" stop-color="%s"/><stop offset="1" stop-color="%s"/></linearGradient>'
                 % (color("raised", "light"), color("hover", "light")))
        fill = "url(#f)"
    else:
        fill = color("raised", "dark")
    body = '<path d="%s" fill="%s" filter="url(#s)"/>' % (continuous_rect(o, o, b, b, a["radius"]), fill)
    small = APPLE_SMALL.get(size)
    width = small["mark"] if small else a["mark"]
    return svg((0, 0, c, c), body + mark_svg(c / 2, c / 2, width, palette(mode), small), size, defs)


def appiconset():
    out = {}
    for px in sorted({pt * scale for pt, scale in MACOS_SLOTS}):
        out[APPICONSET + "/app_icon_%d.png" % px] = ("png", apple_svg(px, "light"), px)
    contents = {
        "images": [
            {"size": "%dx%d" % (pt, pt), "idiom": "mac", "filename": "app_icon_%d.png" % (pt * scale),
             "scale": "%dx" % scale}
            for pt, scale in MACOS_SLOTS
        ],
        "info": {"version": 1, "author": "xcode"},
    }
    out[APPICONSET + "/Contents.json"] = ("text", json.dumps(contents, indent=2, separators=(",", " : ")) + "\n")
    return out


def srgb(hex_):
    r, g, b = (int(hex_[i:i + 2], 16) / 255 for i in (1, 3, 5))
    return "srgb:%.5f,%.5f,%.5f,1.00000" % (r, g, b)


def icon_bundle():
    """The Icon Composer document: the body is the document's fill (macOS
    draws it as the whole icon shape, so the mark keeps its share of the
    appiconset's body), and each arc and the dot is a layer of its own, a
    1024 canvas with the shape in place, the arcs as outlines. Light and
    dark are fills; tinted draws the shapes in white for the system to
    tint."""
    c = APPLE["canvas"]
    width = APPLE["mark"] * c / APPLE["body"]
    tx, ty, s = placed(c / 2, c / 2, width)
    g = '<g transform="translate(%s %s) scale(%s)">%%s</g>' % (n(tx), n(ty), n(s))
    shapes = {
        "you": '<path d="%s" fill="#000000"/>' % outline(mark["you"]["d"], mark["stroke"]),
        "agent": '<path d="%s" fill="#000000"/>' % outline(mark["agent"]["d"], mark["stroke"]),
        "dot": '<path d="%s" fill="#000000"/>' % DOT_D,
    }
    light, dark = palette("light"), palette("dark")

    def layer(name):
        return {
            "name": name,
            "image-name": name + ".svg",
            "glass": False,
            "fill-specializations": [
                {"value": {"solid": srgb(light[name])}},
                {"appearance": "dark", "value": {"solid": srgb(dark[name])}},
                {"appearance": "tinted", "value": {"solid": srgb("#ffffff")}},
            ],
        }

    doc = {
        "fill-specializations": [
            {"value": {"linear-gradient": [srgb(color("raised", "light")), srgb(color("hover", "light"))],
                       "orientation": {"start": {"x": 0.5, "y": 0}, "stop": {"x": 0.5, "y": 1}}}},
            {"appearance": "dark", "value": {"solid": srgb(color("raised", "dark"))}},
        ],
        "groups": [{
            "layers": [layer("dot"), layer("agent"), layer("you")],
            "shadow": {"kind": "neutral", "opacity": 0.5},
            "translucency": {"enabled": False, "value": 0.5},
        }],
        "supported-platforms": {"squares": "shared"},
    }
    out = {ICON + "/icon.json": ("text", json.dumps(doc, indent=2, separators=(",", " : ")) + "\n")}
    for name, shape in shapes.items():
        out[ICON + "/Assets/%s.svg" % name] = ("text", svg((0, 0, c, c), g % shape))
    return out


# Each target maps output paths to ("text", content) or ("png", svg, px).
TARGETS = [android, appiconset, icon_bundle]


def outputs():
    out = {}
    for t in TARGETS:
        out.update(t())
    out[HASH] = ("text", "# The sha256 of what scripts/build-app-icons.sh rendered the icons from:\n"
                 "# design/mark.json, the colours %s of design/tokens.json, and the script.\n%s\n"
                 % (", ".join(COLORS), source_hash()))
    return out


# --- Running ----------------------------------------------------------------

def renderer():
    env = os.environ.get("RSVG_CONVERT", "")
    if env:
        if os.access(env, os.X_OK):
            return env
        die("rsvg-convert not found at RSVG_CONVERT=%s" % env)
    found = shutil.which("rsvg-convert")
    for prefix in ("/opt/homebrew", "/usr/local", os.path.expanduser("~/.local/homebrew")):
        if found:
            break
        p = os.path.join(prefix, "bin", "rsvg-convert")
        found = p if os.access(p, os.X_OK) else None
    if not found:
        die("rsvg-convert not found (install librsvg: brew install librsvg; or set RSVG_CONVERT)")
    return found


def render(rsvg, svg_text, px, dest, tmp):
    src = os.path.join(tmp, "in.svg")
    with open(src, "w") as f:
        f.write(svg_text)
    subprocess.run([rsvg, "-w", str(px), "-h", str(px), "-o", dest, src], check=True)


def write(path, data):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w") as f:
        f.write(data)


def check():
    stale = []
    for path, out in sorted(outputs().items()):
        full = os.path.join(ROOT, path)
        if out[0] == "png":
            if not os.path.isfile(full):
                stale.append(path + " (missing)")
            continue
        try:
            have = read(path).decode()
        except FileNotFoundError:
            have = None
        if have != out[1]:
            stale.append(path + (" (missing)" if have is None else ""))
    if stale:
        for s in stale:
            print("stale: " + s, file=sys.stderr)
        die("the icons are not what their source renders; run scripts/build-app-icons.sh")


def build():
    rsvg = renderer()
    outs = outputs()
    with tempfile.TemporaryDirectory() as tmp:
        staged = {}
        for i, (path, out) in enumerate(sorted(outs.items())):
            if out[0] == "png":
                staged[path] = os.path.join(tmp, "%d.png" % i)
                render(rsvg, out[1], out[2], staged[path], tmp)
        # The .icon bundle holds only what this run writes.
        shutil.rmtree(os.path.join(ROOT, ICON), ignore_errors=True)
        for path, png in staged.items():
            os.makedirs(os.path.dirname(os.path.join(ROOT, path)), exist_ok=True)
            shutil.move(png, os.path.join(ROOT, path))
    # The hash goes last: a run cut short leaves it stale.
    for path, out in sorted(outs.items(), key=lambda kv: kv[0] == HASH):
        if out[0] == "text":
            write(path, out[1])


def preview(dest):
    rsvg = renderer()
    os.makedirs(dest, exist_ok=True)
    light = palette("light")
    bg = color("bg", "light")
    shots = {}
    for shape in ("circle", "squircle", "rounded", "teardrop", "square"):
        shots["icon-mask-%s.png" % shape] = (adaptive_svg(432, shape, bg, light), 432)
    shots["icon-safe-zone.png"] = (adaptive_svg(432, "square", bg, light, guide=True), 432)
    for mode in ("light", "dark"):
        tint = {"you": color("agent-ink", mode), "agent": color("agent-ink", mode), "dot": color("agent-ink", mode)}
        shots["icon-mono-%s.png" % mode] = (adaptive_svg(432, "circle", color("accent-tint", mode), tint), 432)
        for px in (1024, 64, 32, 16):
            shots["mac-%s-%d.png" % (mode, px)] = (apple_svg(px, mode), px)
    with tempfile.TemporaryDirectory() as tmp:
        for name, (s, px) in shots.items():
            render(rsvg, s, px, os.path.join(dest, name), tmp)
            print(os.path.join(dest, name))


