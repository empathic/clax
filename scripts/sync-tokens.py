class MarkError(Exception):
    pass


def arc_path(name, d):
    """The Dart Path builder of an SVG path of M/m and A/a commands."""
    if not re.fullmatch(r"\s*(?:[MmAa][-\d\s.,]*)+", d):
        raise MarkError("design/mark.json: %s.d has a command other than M or A: %r" % (name, d))
    tokens = re.findall(r"[MmAa]|-?(?:\d+\.?\d*|\.\d+)", d)
    try:
        return "Path()" + "".join(_arc_steps(name, tokens))
    except (IndexError, ValueError):
        raise MarkError("design/mark.json: %s.d is short of a command's numbers: %r" % (name, d))


def _arc_steps(name, tokens):
    out, x, y, i = [], 0.0, 0.0, 0
    while i < len(tokens):
        cmd = tokens[i]
        i += 1
        if cmd in "Mm":
            dx, dy = float(tokens[i]), float(tokens[i + 1])
            i += 2
            x, y = (x + dx, y + dy) if cmd == "m" else (dx, dy)
            out.append("..moveTo(%s, %s)" % (num(round(x, 6)), num(round(y, 6))))
        elif cmd in "Aa":
            rx, ry, rot, large, sweep, ex, ey = (float(v) for v in tokens[i : i + 7])
            i += 7
            x, y = (x + ex, y + ey) if cmd == "a" else (ex, ey)
            out.append(
                "..arcToPoint(const Offset(%s, %s), radius: const Radius.elliptical(%s, %s), rotation: %s, largeArc: %s, clockwise: %s)"
                % (
                    num(round(x, 6)),
                    num(round(y, 6)),
                    num(rx),
                    num(ry),
                    num(rot),
                    "true" if large else "false",
                    "true" if sweep else "false",
                )
            )
        else:
            raise MarkError("design/mark.json: %s.d: %r is not a command" % (name, cmd))
    return out


