def surface_containers():
    """The home app's names for the surface container steps, lowest first."""
    return ["surface-container" + ("-" + n if n else "") for n in CONTAINER_NAMES]


def kit_value(tokens, ref, theme):
    """The CSS value of a "kit" map entry: the home app's property name it
    names (a colour, surface-container[-<step>], radius, radius-<name>,
    t-fast, t, t-enter, t-exit, font, mono, serif or type-<role>), or a
    motion curve's name."""
    d = tokens.data
    motion = d["motion"]
    if ref in tokens.color:
        return tokens.value(ref, theme)
    if ref in surface_containers():
        return d["surfaceContainers"][theme][surface_containers().index(ref)]
    if ref == "radius":
        return num(d["radius"]["md"]) + "px"
    if ref.startswith("radius-") and ref[len("radius-") :] in d["radius"]:
        return num(d["radius"][ref[len("radius-") :]]) + "px"
    if ref in ("t-fast", "t", "t-enter", "t-exit"):
        return "%sms" % motion[ref]["ms"]
    if ref in motion["curves"]:
        return "cubic-bezier(%s)" % ",".join(num(x) for x in motion["curves"][ref])
    if ref in ("font", "mono", "serif"):
        return d["font"]["web"]["sans" if ref == "font" else ref]
    if ref.startswith("type-") and ref[len("type-") :] in d["type"]:
        t = d["type"][ref[len("type-") :]]
        size, line, weight = t["material"]
        family = {"mono": "--k-font-mono", "serif": "--k-font-serif"}.get(t.get("family"), "--k-font")
        style = "italic " if t.get("italic") else ""
        return "%s%s %spx/%spx var(%s)" % (style, weight, num(size), num(line), family)
    raise KitError("design/tokens.json: kit names %s, which is no token" % ref)


def kit_region(tokens):
    """The text between kit.css's markers: :root, both dark blocks, and
    prefers-contrast: more."""
    kit = tokens.data["kit"]
    themed = [k for k, ref in kit.items() if ref in tokens.color or ref in surface_containers()]

    def block(theme, names, indent):
        return "\n".join("%s%s: %s;" % (indent, k, kit_value(tokens, kit[k], theme)) for k in names)

    more = []
    for weak, strong in tokens.data.get("contrastMore", {}).items():
        # The stronger key named after the weak one (--k-line-strong for
        # --k-line), else the first.
        stronger = [k for k, ref in kit.items() if ref == strong]
        for k, ref in kit.items():
            if ref != weak:
                continue
            if not stronger:
                raise KitError("design/tokens.json: kit has %s for %s but nothing for %s" % (k, weak, strong))
            more.append("    %s: var(%s);" % (k, next((s for s in stronger if s.startswith(k)), stronger[0])))

    aliases = tokens.data.get("kitAliases", {})
    head = "  --k-version: %s;\n" % num(tokens.kit_version) if tokens.kit_version is not None else ""
    tail = "".join("\n  %s: var(%s);" % (old, new) for old, new in aliases.items())
    return (
        ":root {\n"
        + head
        + block("light", list(kit), "  ")
        + tail
        + "\n}\n"
        + "@media (prefers-color-scheme: dark) {\n"
        + '  :root:not([data-theme="light"]) {\n'
        + block("dark", themed, "    ")
        + "\n  }\n}\n"
        + ':root[data-theme="dark"] {\n'
        + block("dark", themed, "  ")
        + "\n}\n"
        + "@media (prefers-contrast: more) {\n"
        # As specific as the dark blocks, and after them.
        + '  :root, :root[data-theme], :root:not([data-theme="light"]) {\n'
        + "\n".join(more)
        + "\n  }\n}\n"
    )


def kit_api_problems(tokens, ledger):
    """Problems with the kit's public API against design/kit-api.json, the
    append-only ledger of every --k-* name a published page may read: a
    published name the source no longer sets (keep it in kitAliases), a name
    the ledger lacks, an alias to no kit name, a name newer than the
    ledger's version, and a version no name carries."""
    if ledger is None:
        return ["%s: missing" % KIT_API]
    kit, aliases = tokens.data["kit"], tokens.data.get("kitAliases", {})
    names, version = ledger["names"], ledger["version"]
    have = set(kit) | set(aliases) | {"--k-version"}
    out = []
    for name in names:
        if name not in have:
            out.append(
                "kit: %s is published (kit API v%s) and design/tokens.json no longer sets it: map it in kitAliases"
                % (name, num(names[name]))
            )
    for name in list(kit) + list(aliases):
        if name not in names:
            out.append("kit: %s is not in %s: add it at version %s and set version to that" % (name, KIT_API, num(version + 1)))
    for old, new in aliases.items():
        if new not in kit:
            out.append("kit: alias %s names %s, which the kit map does not set" % (old, new))
    if any(v > version for v in names.values()):
        out.append("%s: a name is newer than version %s" % (KIT_API, num(version)))
    elif names and max(names.values()) != version:
        out.append("%s: version is %s, and no name was added at it" % (KIT_API, num(version)))
    return out


def kit_css(tokens, css):
    """kit.css with its generated region rewritten."""
    try:
        return with_region("kit.css", css, kit_region(tokens))
    except RegionError as e:
        raise KitError(str(e))


def css_walk(css):
    """The color-mix() calls and the custom property declarations of css,
    as (kind, name, line, inside @supports): kind "mix" (name None) or
    "decl" (name the property)."""
    css = re.sub(r"/\*.*?\*/", lambda m: re.sub(r"[^\n]", " ", m.group(0)), css, flags=re.S)
    stack, statement, line, i = [], "", 1, 0
    while i < len(css):
        c = css[i]
        supports = statement.lstrip().startswith("@supports") or any(stack)
        if css.startswith("color-mix(", i):
            yield ("mix", None, line, supports)
        if c in "{};":
            m = re.match(r"\s*(--[a-z0-9-]+)\s*:", statement)
            if m and c != "{":
                yield ("decl", m.group(1), line, any(stack))
        if c == "{":
            stack.append(statement.lstrip().startswith("@supports"))
            statement = ""
        elif c == "}":
            if stack:
                stack.pop()
            statement = ""
        elif c == ";":
            statement = ""
        else:
            statement += c
        if c == "\n":
            line += 1
        i += 1


def unguarded_mixes(name, css, first_line=1):
    """Problems for each color-mix() in css (whose first line is
    first_line of the file called name) outside an @supports block."""
    return [
        "%s: color-mix() outside @supports at line %d" % (name, line + first_line - 1)
        for kind, _, line, supports in css_walk(css)
        if kind == "mix" and not supports
    ]


def kit_unguarded_mixes(css):
    return unguarded_mixes("kit.css", css)


def kit_redeclared(tokens, css):
    """Problems for each "kit" map token kit.css declares outside its
    generated region and outside an @supports block."""
    begin = css.find(KIT_BEGIN)
    end = css.find(KIT_END, begin)
    if begin < 0 or end < 0:
        return []
    # The region blanked, its lines kept.
    rest = css[:begin] + re.sub(r"[^\n]", " ", css[begin:end]) + css[end:]
    names = set(tokens.data["kit"]) | set(tokens.data.get("kitAliases", {})) | {"--k-version"}
    return [
        "kit.css: %s is declared outside its generated region at line %d" % (name, line)
        for kind, name, line, supports in css_walk(rest)
        if kind == "decl" and name in names and not supports
    ]


def map_css(js):
    """The stylesheet map.js adds to the page (its `const CSS` template),
    and the line of map.js it starts on; (None, 0) without one."""
    m = re.search(r"const CSS = `(.*?)`;", js or "", flags=re.S)
    if not m:
        return None, 0
    return m.group(1), js.count("\n", 0, m.start(1)) + 1


def reel_curves(tokens, pace):
    """Problems with the reel's `CURVES` in web/reel/pace.ts: each must be
    a motion curve of the same name and control points, and every motion
    curve must be there."""
    m = re.search(r"export const CURVES = \{(.*?)\}", pace or "", flags=re.S)
    if not m:
        return ["%s: no `export const CURVES = {...}`" % REEL_PACE]
    have = {
        name: [float(x) for x in values.split(",")]
        for name, values in re.findall(r"(\w+):\s*\[([^\]]*)\]", m.group(1))
    }
    want = {name: [float(x) for x in c] for name, c in tokens.data["motion"]["curves"].items()}
    if have == want:
        return []
    return ["%s: CURVES is %s; %s's motion.curves are %s" % (REEL_PACE, have, SOURCE, want)]


