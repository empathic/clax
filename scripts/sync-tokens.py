#!/usr/bin/env python3
"""Writes the brand's token files from design/tokens.json.

Writes:
  apps/clax_app/home/tokens.css     the home app's custom properties
  apps/clax_app/lib/ui/tokens.g.dart  Flutter's palettes, type, space,
                                    layout, radii, elevation and motion
  apps/clax_app/assets/haiku.json   a copy of web/shell/src/view/haiku.json

and checks, in both modes, that every pair under "contrast" meets its
minimum (WCAG 2.x, a translucent colour composited on the pair's
background) and that web/shell/src/theme.css gives each "appMode" colour
the source's value.

Usage: scripts/sync-tokens.py [--check]
  --check  writes nothing; exits 1 with a diff when an output differs.
"""

import difflib
import json
import os
import re
import sys

CSS_HEADER = "/* Generated by scripts/sync-tokens.py from design/tokens.json. Do not edit. */\n"
DART_HEADER = "// Generated by scripts/sync-tokens.py from design/tokens.json. Do not edit.\n"

HOME_CSS = "apps/clax_app/home/tokens.css"
DART = "apps/clax_app/lib/ui/tokens.g.dart"
HAIKU = "apps/clax_app/assets/haiku.json"
HAIKU_SOURCE = "web/shell/src/view/haiku.json"
THEME_CSS = "web/shell/src/theme.css"
SOURCE = "design/tokens.json"

THEMES = ("light", "dark")
CONTAINER_NAMES = ("lowest", "low", "", "high", "highest")


def repo_root():
    """The runfiles tree under `bazel test`, else this script's parent directory."""
    srcdir, workspace = os.environ.get("TEST_SRCDIR"), os.environ.get("TEST_WORKSPACE")
    if srcdir and workspace:
        return os.path.join(srcdir, workspace)
    return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


# Values


def num(x):
    """A number as the outputs write it: an integer without a point."""
    if isinstance(x, float) and x.is_integer():
        x = int(x)
    return str(x)


def camel(name):
    head, *rest = name.split("-")
    return head + "".join(p[:1].upper() + p[1:] for p in rest)


def parse_color(text):
    """(r, g, b, a) of '#rrggbb' or 'rgba(r,g,b,a)', a in 0..1."""
    text = text.strip().lower()
    m = re.fullmatch(r"#([0-9a-f]{6})", text)
    if m:
        v = m.group(1)
        return (int(v[0:2], 16), int(v[2:4], 16), int(v[4:6], 16), 1.0)
    m = re.fullmatch(r"rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([0-9.]+)\s*\)", text)
    if m:
        return (int(m.group(1)), int(m.group(2)), int(m.group(3)), float(m.group(4)))
    raise ValueError("not a colour: %r" % text)


def dart_color(text):
    r, g, b, a = parse_color(text)
    return "Color(0x%02X%02X%02X%02X)" % (round(a * 255), r, g, b)


class Tokens:
    def __init__(self, data):
        self.data = data
        self.color = data["color"]

    def is_alias(self, name):
        return isinstance(self.color[name], str)

    def concrete(self):
        """The colour names that carry values, in the source's order."""
        return [n for n in self.color if not self.is_alias(n)]

    def resolve(self, name):
        seen = set()
        while self.is_alias(name):
            if name in seen:
                raise ValueError("alias loop at %s" % name)
            seen.add(name)
            name = self.color[name]
        return name

    def value(self, name, theme, more=False):
        if more and name in self.data.get("contrastMore", {}):
            name = self.data["contrastMore"][name]
        return self.color[self.resolve(name)][theme]


# Contrast


def luminance(rgb):
    def channel(c):
        c = c / 255
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4

    r, g, b = (channel(c) for c in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def composite(top, under):
    r, g, b, a = top
    return tuple(a * t + (1 - a) * u for t, u in zip((r, g, b), under[:3]))


def contrast(fg, bg, page):
    """WCAG 2.x ratio of fg on bg; a translucent bg sits on page first."""
    back = composite(bg, page) if bg[3] < 1 else bg[:3]
    fore = composite(fg, back + (1.0,))
    lighter, darker = sorted((luminance(fore), luminance(back)), reverse=True)
    return (lighter + 0.05) / (darker + 0.05)


def contrast_failures(tokens):
    out = []
    for pair in tokens.data.get("contrast", []):
        for theme in pair["themes"]:
            page = parse_color(tokens.value("bg", theme))
            ratio = contrast(
                parse_color(tokens.value(pair["fg"], theme)),
                parse_color(tokens.value(pair["bg"], theme)),
                page,
            )
            if ratio < pair["min"]:
                out.append(
                    "contrast: %s on %s (%s) is %.2f, below %s"
                    % (pair["fg"], pair["bg"], theme, ratio, num(pair["min"]))
                )
    return out


# theme.css's app-mode colours


def css_block(css, selector):
    """The declarations of the first block whose opening line starts with selector."""
    lines = css.split("\n")
    for i, line in enumerate(lines):
        if line.startswith(selector):
            body = []
            for rest in lines[i + 1 :]:
                if rest.startswith("}"):
                    return "\n".join(body)
                body.append(rest)
    return None


def declarations(block):
    return {m.group(1): m.group(2).strip() for m in re.finditer(r"--([a-z0-9-]+)\s*:\s*([^;]+);", block or "")}


def check_app_mode(tokens, theme_css):
    light = declarations(css_block(theme_css, ":root {"))
    darks = [
        declarations(css_block(theme_css, ':root:not([data-theme="light"])')),
        declarations(css_block(theme_css, ':root[data-theme="dark"]')),
    ]
    out = []

    def same(css_value, token_value):
        try:
            return parse_color(css_value) == parse_color(token_value)
        except ValueError:
            return False

    for name in tokens.data.get("appMode", []):
        want_light, want_dark = tokens.value(name, "light"), tokens.value(name, "dark")
        got = light.get(name)
        if got is None:
            out.append("theme.css: --%s is missing, design/tokens.json says %s" % (name, want_light))
            continue
        if not same(got, want_light):
            out.append("theme.css: --%s is %s, design/tokens.json says %s" % (name, got, want_light))
        for dark in darks:
            got_dark = dark.get(name, got)
            if not same(got_dark, want_dark):
                out.append(
                    "theme.css: --%s is %s (dark), design/tokens.json says %s" % (name, got_dark, want_dark)
                )
                break
    return out


# The home app's CSS


def home_css(tokens):
    d = tokens.data
    web = d["font"]["web"]

    def colours(theme):
        lines = []
        for name in tokens.concrete():
            lines.append("  --%s: %s;" % (name, tokens.color[name][theme]))
        for i, c in enumerate(d["surfaceContainers"][theme]):
            suffix = "-" + CONTAINER_NAMES[i] if CONTAINER_NAMES[i] else ""
            lines.append("  --surface-container%s: %s;" % (suffix, c))
        for level, e in d["elevation"].items():
            lines.append("  --elev-%s: %s;" % (level, e[theme]))
        return lines

    def curve(name):
        c = d["motion"]["curves"].get(name)
        if c is None:
            return name
        return "cubic-bezier(%s)" % ",".join(num(x) for x in c)

    root = colours("light")
    for name in tokens.color:
        if tokens.is_alias(name):
            root.append("  --%s: var(--%s);" % (name, tokens.color[name]))
    root.append("  --font: %s;" % web["sans"])
    root.append("  --mono: %s;" % web["mono"])
    root.append("  --serif: %s;" % web["serif"])
    for role, t in d["type"].items():
        size, line, weight = t["material"]
        family = {"mono": "--mono", "serif": "--serif"}.get(t.get("family"), "--font")
        style = "italic " if t.get("italic") else ""
        root.append("  --type-%s: %s%s %spx/%spx var(%s);" % (role, style, weight, num(size), num(line), family))
    for s in d["space"]:
        root.append("  --space-%s: %s;" % (num(s), num(s) + "px" if s else "0"))
    for name, r in d["radius"].items():
        prop = "--radius" if name == "md" else "--radius-" + name
        value = "%s%%" % num(r * 100) if name == "tile" else num(r) + "px"
        root.append("  %s: %s;" % (prop, value))
    for name in ("t-fast", "t", "t-enter", "t-exit"):
        m = d["motion"][name]
        root.append("  --%s: %sms %s;" % (name, m["ms"], curve(m["curve"])))

    dark = colours("dark")
    more = ["  --%s: var(--%s);" % (a, b) for a, b in d.get("contrastMore", {}).items()]
    return (
        CSS_HEADER
        + ":root {\n"
        + "\n".join(root)
        + "\n}\n"
        + "@media (prefers-color-scheme: dark) {\n"
        + '  :root:not([data-theme="light"]) {\n'
        + "\n".join("  " + x for x in dark)
        + "\n  }\n}\n"
        + ':root[data-theme="dark"] {\n'
        + "\n".join(dark)
        + "\n}\n"
        + "@media (prefers-contrast: more) {\n"
        # As specific as the dark blocks, and after them.
        + '  :root, :root[data-theme], :root:not([data-theme="light"]) {\n'
        + "\n".join("  " + x for x in more)
        + "\n  }\n}\n"
    )


# Flutter


def dart_shadows(text):
    """BoxShadow constructors of a CSS box-shadow list ('x y blur colour, …')."""
    out = []
    for m in re.finditer(r"(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+([\d.]+)(?:px)?\s+(rgba\([^)]*\)|#[0-9a-fA-F]{6})", text):
        x, y, blur, colour = m.groups()
        out.append(
            "BoxShadow(color: %s, offset: Offset(%s, %s), blurRadius: %s)"
            % (dart_color(colour), num(float(x)), num(float(y)), num(float(blur)))
        )
    return out


def dart(tokens):
    d = tokens.data
    fields = [camel(n) for n in tokens.concrete()] + list(d["scheme"])

    def palette(theme, more):
        args = []
        for name in tokens.concrete():
            args.append("    %s: %s," % (camel(name), dart_color(tokens.value(name, theme, more))))
        for name, v in d["scheme"].items():
            args.append("    %s: %s," % (name, dart_color(v[theme])))
        containers = ", ".join(dart_color(c) for c in d["surfaceContainers"][theme])
        args.append("    surfaceContainers: [%s]," % containers)
        return "ClaxPalette(\n" + "\n".join(args) + "\n  )"

    roles = list(d["type"])
    fonts = d["font"]

    def style(t, metrics, family_set):
        size, line, weight = metrics
        families = fonts[family_set][t.get("family", "sans")]
        parts = ["fontSize: %s" % num(size), "height: %s / %s" % (num(line), num(size))]
        parts.append("fontWeight: FontWeight.w%d" % weight)
        parts.append("letterSpacing: 0")
        if t.get("italic"):
            parts.append("fontStyle: FontStyle.italic")
        if families:
            parts.append("fontFamily: '%s'" % families[0])
        if len(families) > 1:
            parts.append("fontFamilyFallback: [%s]" % ", ".join("'%s'" % f for f in families[1:]))
        return "    TextStyle(%s)," % ", ".join(parts)

    material = [style(d["type"][r], d["type"][r]["material"], "material") for r in roles]
    macos = [style(d["type"][r], d["type"][r]["apple"]["macos"], "apple") for r in roles]
    ios = [
        style(d["type"][r], d["type"][r]["apple"].get("ios", d["type"][r]["apple"]["macos"]), "apple") for r in roles
    ]

    space = ", ".join("s%s = %s" % (num(s), num(s)) for s in d["space"])
    layout = ", ".join("%s = %s" % (k, num(v)) for k, v in d["layout"].items())
    radius = ", ".join(
        "%s = %s" % (camel(k), num(v)) for k, v in d["radius"].items() if k != "tile"
    )

    elevation = d["elevation"]
    levels = sorted(int(k) for k in elevation)
    shadow_cases = []
    for theme, brightness in (("light", "light"), ("dark", "dark")):
        for level in levels:
            shadows = dart_shadows(elevation[str(level)][theme])
            shadow_cases.append(
                "      (%d, Brightness.%s) => const [%s]," % (level, brightness, ", ".join(shadows))
            )
    surface_cases = ["      0 => p.bg,"] + [
        "      %d => p.%s," % (level, camel(elevation[str(level)]["surface"])) for level in levels
    ]
    border_cases = [
        "      %d => p.%s," % (level, camel(elevation[str(level)]["darkBorder"])) for level in levels
    ]

    motion = d["motion"]

    def ms(name):
        return "Duration(milliseconds: %d)" % motion[name]["ms"]

    curves = "\n".join(
        "  static const Curve %s = Cubic(%s);" % (name, ", ".join(num(x) for x in c))
        for name, c in motion["curves"].items()
    )

    return (
        DART_HEADER
        + "\n"
        + "import 'package:flutter/widgets.dart';\n"
        + "\n"
        + "/// The brand's colours for one theme.\n"
        + "final class ClaxPalette {\n"
        + "  const ClaxPalette({\n"
        + "".join("    required this.%s,\n" % f for f in fields)
        + "    required this.surfaceContainers,\n"
        + "  });\n\n"
        + "".join("  final Color %s;\n" % f for f in fields)
        + "\n  /// Material's surface containers, lowest to highest.\n"
        + "  final List<Color> surfaceContainers;\n"
        + "}\n\n"
        + "/// The palettes: each theme, and each with more contrast (a hairline\n"
        + "/// takes `borderStrong`).\n"
        + "abstract final class ClaxTokens {\n"
        + "  static const ClaxPalette light = %s;\n\n" % palette("light", False)
        + "  static const ClaxPalette dark = %s;\n\n" % palette("dark", False)
        + "  static const ClaxPalette lightMore = %s;\n\n" % palette("light", True)
        + "  static const ClaxPalette darkMore = %s;\n" % palette("dark", True)
        + "}\n\n"
        + "/// The type roles.\n"
        + "enum ClaxRole { %s }\n\n" % ", ".join(camel(r) for r in roles)
        + "/// Each role's size, line height and weight. Letter-spacing is 0 throughout;\n"
        + "/// colour is the caller's (the haiku is `muted`).\n"
        + "abstract final class ClaxType {\n"
        + "  /// [role] on [platform]: the material column, or the apple entry for\n"
        + "  /// the platform (macOS; iOS once the source gives it, else macOS).\n"
        + "  static TextStyle of(ClaxRole role, TargetPlatform platform) => switch (platform) {\n"
        + "        TargetPlatform.macOS => _macos[role.index],\n"
        + "        TargetPlatform.iOS => _ios[role.index],\n"
        + "        _ => _material[role.index],\n"
        + "      };\n\n"
        + "  /// The mono role in the platform's monospace family.\n"
        + "  static TextStyle mono(TargetPlatform platform) => of(ClaxRole.mono, platform);\n\n"
        + "  static const List<TextStyle> _material = [\n" + "\n".join(material) + "\n  ];\n\n"
        + "  static const List<TextStyle> _macos = [\n" + "\n".join(macos) + "\n  ];\n\n"
        + "  static const List<TextStyle> _ios = [\n" + "\n".join(ios) + "\n  ];\n"
        + "}\n\n"
        + "/// The 4-point space scale.\n"
        + "abstract final class ClaxSpace {\n"
        + "  static const double %s;\n" % space
        + "}\n\n"
        + "/// Gutters, content widths, window size class breakpoints, pane widths\n"
        + "/// and targets.\n"
        + "abstract final class ClaxLayout {\n"
        + "  static const double %s;\n" % layout
        + "}\n\n"
        + "/// Corner radii.\n"
        + "abstract final class ClaxRadius {\n"
        + "  static const double %s;\n\n" % radius
        + "  /// An app icon's corner in a grid, for an icon [size] across.\n"
        + "  static double tile(double size) => size * %s;\n" % num(d["radius"]["tile"])
        + "}\n\n"
        + "/// Elevation levels 0 to 3: shadows, and in dark a lighter surface and a\n"
        + "/// 1 px outline, since shadows do not show on dark.\n"
        + "abstract final class ClaxElevation {\n"
        + "  /// The shadows of [level] in brightness [b].\n"
        + "  static List<BoxShadow> shadows(int level, Brightness b) => switch ((level, b)) {\n"
        + "      (0, _) => const [],\n"
        + "\n".join(shadow_cases)
        + "\n      _ => throw RangeError.range(level, 0, %d, 'level'),\n" % levels[-1]
        + "    };\n\n"
        + "  /// A surface at [level]: [color] or the level's surface, its shadows and,\n"
        + "  /// in dark, its outline (`border` at 1, `borderHover` above).\n"
        + "  static BoxDecoration of(int level, Brightness b, ClaxPalette p, {Color? color, BorderRadius? radius}) {\n"
        + "    final surface = switch (level) {\n"
        + "\n".join(surface_cases)
        + "\n      _ => throw RangeError.range(level, 0, %d, 'level'),\n" % levels[-1]
        + "    };\n"
        + "    final outline = level == 0 || b == Brightness.light\n"
        + "        ? null\n"
        + "        : switch (level) {\n"
        + "\n".join("    " + c for c in border_cases)
        + "\n          _ => null,\n"
        + "        };\n"
        + "    return BoxDecoration(\n"
        + "      color: color ?? surface,\n"
        + "      borderRadius: radius,\n"
        + "      border: outline == null ? null : Border.all(color: outline),\n"
        + "      boxShadow: shadows(level, b),\n"
        + "    );\n"
        + "  }\n"
        + "}\n\n"
        + "/// Durations and curves.\n"
        + "abstract final class ClaxMotion {\n"
        + "  static const fast = %s, base = %s, enter = %s, exit = %s, markBreath = %s;\n"
        % (ms("t-fast"), ms("t"), ms("t-enter"), ms("t-exit"), ms("mark-breath"))
        + curves
        + "\n\n"
        + "  /// [d], or %d ms when animations are reduced and [d] is longer.\n" % motion["reduced"]
        + "  static Duration of(BuildContext context, Duration d) {\n"
        + "    const reduced = Duration(milliseconds: %d);\n" % motion["reduced"]
        + "    return MediaQuery.disableAnimationsOf(context) && d > reduced ? reduced : d;\n"
        + "  }\n"
        + "}\n"
    )


# Main


def read(root, path, binary=False):
    full = os.path.join(root, path)
    if not os.path.exists(full):
        return None
    with open(full, "rb" if binary else "r", encoding=None if binary else "utf-8", newline=None if binary else "") as f:
        return f.read()


def main(argv):
    check = False
    if argv == ["--check"]:
        check = True
    elif argv:
        print("usage: sync-tokens.py [--check]", file=sys.stderr)
        return 2
    root = repo_root()
    tokens = Tokens(json.loads(read(root, SOURCE)))

    problems = contrast_failures(tokens) + check_app_mode(tokens, read(root, THEME_CSS))
    outputs = {
        HOME_CSS: home_css(tokens).encode(),
        DART: dart(tokens).encode(),
        HAIKU: read(root, HAIKU_SOURCE, binary=True),
    }

    stale = []
    for path, want in outputs.items():
        have = read(root, path, binary=True)
        if have == want:
            continue
        stale.append(path)
        if check:
            diff = difflib.unified_diff(
                (have or b"").decode("utf-8", "replace").splitlines(keepends=True),
                want.decode().splitlines(keepends=True),
                fromfile="a/" + path,
                tofile="b/" + path,
            )
            print("%s is stale; run python3 scripts/sync-tokens.py" % path)
            sys.stdout.writelines(diff)
            print()

    for p in problems:
        print(p)
    if problems:
        return 1
    if check:
        return 1 if stale else 0
    for path in stale:
        full = os.path.join(root, path)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "wb") as f:
            f.write(outputs[path])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
