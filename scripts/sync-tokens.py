def read(root, path, binary=False):
    full = os.path.join(root, path)
    if not os.path.exists(full):
        return None
    with open(full, "rb" if binary else "r", encoding=None if binary else "utf-8", newline=None if binary else "") as f:
        return f.read()


def main(argv):
    check = False
    if argv == ["--check"]:
        check = True
    elif argv:
        print("usage: sync-tokens.py [--check]", file=sys.stderr)
        return 2
    root = repo_root()
    tokens = Tokens(json.loads(read(root, SOURCE)))

    problems = schema_problems(tokens)
    if problems:
        for p in problems:
            print(p)
        return 1
    problems = contrast_failures(tokens)
    problems += live_palette(tokens, read(root, LIVE_TS))
    ledger_text = read(root, KIT_API)
    ledger = json.loads(ledger_text) if ledger_text is not None else None
    if ledger is not None:
        tokens.kit_version = ledger["version"]
    problems += kit_api_problems(tokens, ledger)
    outputs = {}
    for path, body, indent, header in (
        (THEME_CSS, shell_region(tokens), "", KIT_HEADER),
        # The SDK package ships the overlay's CSS unminified: its own head
        # comment says the region is generated.
        (OVERLAY_CSS, overlay_region(tokens), "", ""),
        (LIVE_SVELTE, live_region(tokens), "    ", KIT_HEADER),
    ):
        try:
            outputs[path] = with_region(path, read(root, path), body, indent, header).encode()
        except RegionError as e:
            problems.append(str(e))
    outputs.update({
        HOME_CSS: home_css(tokens).encode(),
        HAIKU: read(root, HAIKU_SOURCE, binary=True),
        GALLERY_PAIRS: pairs_json(tokens),
    })
    geometry = ""
    try:
        mark_css, geometry = mark_outputs(json.loads(read(root, MARK)), read(root, MARK_CSS))
        outputs.update(mark_css)
    except MarkError as e:
        problems.append(str(e))
    outputs[DART] = (dart(tokens) + geometry).encode()
    try:
        kit = kit_css(tokens, read(root, KIT_CSS) or "")
        outputs[KIT_CSS] = kit.encode()
        problems += kit_unguarded_mixes(kit)
        problems += kit_redeclared(tokens, kit)
    except KitError as e:
        problems.append(str(e))
    problems += unguarded_mixes("home.css", read(root, HOME_APP_CSS) or "")
    problems += reel_curves(tokens, read(root, REEL_PACE))
    css, first = map_css(read(root, MAP_JS))
    if css is not None:
        problems += unguarded_mixes("map.js", css, first)

    stale = []
    for path, want in outputs.items():
        have = read(root, path, binary=True)
        if have == want:
            continue
        stale.append(path)
        if check:
            diff = difflib.unified_diff(
                (have or b"").decode("utf-8", "replace").splitlines(keepends=True),
                want.decode().splitlines(keepends=True),
                fromfile="a/" + path,
                tofile="b/" + path,
            )
            print("%s is stale; run python3 scripts/sync-tokens.py" % path)
            sys.stdout.writelines(diff)
            print()

    for p in problems:
        print(p)
    if problems:
        return 1
    if check:
        return 1 if stale else 0
    for path in stale:
        full = os.path.join(root, path)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "wb") as f:
            f.write(outputs[path])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
